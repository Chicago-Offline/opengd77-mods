#!/usr/bin/env python3
"""Generate chioffSkyline.h - the scrolling Chicago skyline strip.

Emits a column-major, 8-pixel-page bitmap in the same layout the OpenGD77
fonts use, so the firmware can index it with plain shifts:

    byte  = chioffSkylineBitmap[(page * W) + x]
    pixel = (byte >> (y & 7)) & 1,  page = (y >> 3)

A SET bit is a lit pixel. The strip is horizontally tileable.

Usage:
    python3 tools/gen_skyline.py > .../include/user_interface/chioffSkyline.h
"""

import sys

W, H = 240, 56
PAGES = H // 8

# (x, width, height, style)
#   p = plain block      s = block with a setback
#   c = Marina City cob  w = Willis       t = Hancock taper   r = Trump spire
BUILDINGS = [
    (2, 12, 15, "p"), (16, 9, 22, "p"), (27, 16, 27, "s"), (46, 9, 22, "c"),
    (57, 9, 22, "c"), (70, 11, 17, "p"), (84, 24, 40, "w"), (111, 10, 18, "p"),
    (124, 14, 33, "t"), (141, 9, 20, "p"), (153, 12, 36, "r"), (168, 10, 17, "p"),
    (180, 14, 25, "s"), (197, 8, 18, "p"), (208, 12, 22, "p"), (223, 13, 28, "s"),
]

px = [[0] * W for _ in range(H)]


def P(x, y, v=1):
    if 0 <= x < W and 0 <= y < H:
        px[y][x] = v


def box(x, w, h):
    for yy in range(H - h, H):
        for xx in range(x, x + w):
            P(xx, yy)


def antenna(x, length, top):
    for yy in range(H - top - length, H - top):
        P(x, yy)


def build():
    for (x, w, h, st) in BUILDINGS:
        if st == "p":
            box(x, w, h)
        elif st == "s":
            box(x, w, int(h * 0.68))
            box(x + 3, w - 6, h)
        elif st == "c":
            box(x, w, h - 3)
            r = w // 2
            for yy in range(H - h, H - h + 4):
                for xx in range(x, x + w):
                    dx = (xx - (x + r)) / max(r, 1)
                    dy = (yy - (H - h + 4)) / 4.0
                    if dx * dx + dy * dy <= 1.2:
                        P(xx, yy)
        elif st == "w":
            box(x, w, int(h * 0.55))
            box(x + 4, w - 8, int(h * 0.78))
            box(x + 8, w - 16, h)
            antenna(x + 9, 12, h)
            antenna(x + 13, 12, h)
        elif st == "t":
            for i in range(h):
                ins = int(i * 2.0 / h * 2)
                for xx in range(x + ins, x + w - ins):
                    P(xx, H - 1 - i)
            antenna(x + 4, 8, h)
            antenna(x + w - 5, 8, h)
        elif st == "r":
            box(x, w, int(h * 0.70))
            box(x + 2, w - 5, h)
            antenna(x + 4, 9, h)

    # punch unlit windows out of the silhouette
    for (x, w, h, st) in BUILDINGS:
        for yy in range(H - h + 3, H - 2, 3):
            for xx in range(x + 2, x + w - 1, 3):
                if px[yy][xx] and px[yy][xx - 1]:
                    P(xx, yy, 0)


def pack():
    out = []
    for page in range(PAGES):
        for x in range(W):
            d = 0
            for r in range(8):
                if px[(page * 8) + r][x]:
                    d |= (1 << r)
            out.append(d)
    return out


HEADER = """/*
 * chioffSkyline.h - Chicago skyline strip for the chioff animated boot screen.
 *
 * Generated by tools/gen_skyline.py (gd77-mods) - do not edit by hand.
 *
 * Column-major, 8-pixel vertical pages, the same layout the OpenGD77 fonts use:
 *     byte  = chioffSkylineBitmap[(page * CHIOFF_SKYLINE_W) + x]
 *     pixel = (byte >> (y & 7)) & 1,  where page = (y >> 3)
 *
 * A SET bit is a lit (foreground) pixel. Note this is the opposite polarity to
 * the codeplug boot image consumed by displayConvertGD77ImageData(), where a
 * set bit paints the background.
 *
 * The strip is horizontally tileable: column (W - 1) joins back to column 0.
 */
#ifndef _OPENGD77_CHIOFF_SKYLINE_H_
#define _OPENGD77_CHIOFF_SKYLINE_H_

#define CHIOFF_SKYLINE_W     %d
#define CHIOFF_SKYLINE_H     %d
#define CHIOFF_SKYLINE_PAGES %d

static const uint8_t chioffSkylineBitmap[CHIOFF_SKYLINE_PAGES * CHIOFF_SKYLINE_W] =
{
%s
};

#endif
"""


def main():
    build()
    data = pack()
    rows = "\n".join(
        "\t" + " ".join("0x%02X," % v for v in data[i:i + 12])
        for i in range(0, len(data), 12)
    )
    sys.stdout.write(HEADER % (W, H, PAGES, rows))


if __name__ == "__main__":
    main()
